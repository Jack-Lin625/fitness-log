import type { BodyPart, Equipment, Exercise, Muscle } from '../types/models';

interface Options {
  /** 自體重量動作：weight 代表額外負重 */
  bw?: boolean;
  /** 輔助機器：weight 代表輔助重量 */
  assisted?: boolean;
}

/** 建立內建動作的小工具，讓下方清單保持簡潔 */
function ex(
  id: string,
  name: string,
  bodyPart: BodyPart,
  equipment: Equipment,
  primaryMuscles: Muscle[],
  secondaryMuscles: Muscle[] = [],
  opts: Options = {},
): Exercise {
  const e: Exercise = {
    id,
    name,
    bodyPart,
    equipment,
    primaryMuscles,
    secondaryMuscles,
    isBodyweight: opts.bw === true || opts.assisted === true,
    isCustom: false,
  };
  if (opts.assisted) e.assisted = true;
  return e;
}

